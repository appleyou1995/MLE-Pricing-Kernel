%% Run the joint common-null simulation for Case 1 and Case 2

function Results = run_simulation_experiment( ...
    Experiment, Data, num_simulations, num_bins_list, ...
    base_seed, batch_size, output_folder)

    num_bins_list = unique(num_bins_list(:)', 'stable');

    if isempty(num_bins_list) || ...
            any(~isfinite(num_bins_list)) || ...
            any(num_bins_list < 2) || ...
            any(num_bins_list ~= round(num_bins_list))
        error('num_bins_list must contain integers greater than one.');
    end

    if num_simulations < 1 || num_simulations ~= round(num_simulations)
        error('num_simulations must be a positive integer.');
    end

    num_bin_settings = numel(num_bins_list);
    Num_Bins_List = num_bins_list;

    Joint_Folder = fullfile( ...
        output_folder, '00_Joint_Null_Simulation');
    Shape_Folder = fullfile( ...
        output_folder, '01_Shape_Null_ConstraintDGP');
    Distortion_Folder = fullfile( ...
        output_folder, ...
        '03_DistortionAlpha_Null_UndistortedDGP');

    folders_to_create = { ...
        output_folder, Joint_Folder, ...
        Shape_Folder, Distortion_Folder};
    for folder_idx = 1:numel(folders_to_create)
        if ~exist(folders_to_create{folder_idx}, 'dir')
            mkdir(folders_to_create{folder_idx});
        end
    end

    checkpoint_file = fullfile( ...
        Joint_Folder, 'Simulation_Checkpoint.mat');
    raw_file = fullfile( ...
        Joint_Folder, 'Simulation_Raw.mat');

    Checkpoint_Settings = struct( ...
        'Version', string(Experiment.Version), ...
        'Experiment_Name', string(Experiment.Name), ...
        'Num_Bins_List', Num_Bins_List, ...
        'Base_Seed', base_seed, ...
        'Sample_Dates', ...
            Data.Realized_Return_Template.date(:), ...
        'b', Data.b, ...
        'Global_Min_R', Data.Global_Min_R, ...
        'Global_Max_R', Data.Global_Max_R, ...
        'ModelNull', Experiment.ModelNull, ...
        'ModelShape', Experiment.ModelShape, ...
        'ModelDistortion', Experiment.ModelDistortion);

    empty_bin_probability = cell(1, num_bin_settings);
    for bin_idx = 1:num_bin_settings
        empty_bin_probability{bin_idx} = ...
            nan(1, num_bins_list(bin_idx));
    end

    empty_result = struct( ...
        'Simulation', NaN, ...
        'LL_Null', NaN, ...
        'LL_Shape', NaN, ...
        'LL_Distortion', NaN, ...
        'LR_Shape', NaN, ...
        'LR_Distortion', NaN, ...
        'SelectedAlpha', NaN, ...
        'SelectedBeta', NaN, ...
        'PIT_Sup_Null', nan(1, num_bin_settings), ...
        'PIT_Sup_Shape', nan(1, num_bin_settings), ...
        'PIT_Sup_Distortion', nan(1, num_bin_settings), ...
        'PIT_Delta_Shape', nan(1, num_bin_settings), ...
        'PIT_Delta_Distortion', nan(1, num_bin_settings), ...
        'KS_Null', NaN, ...
        'KS_Shape', NaN, ...
        'KS_Distortion', NaN, ...
        'ExitFlag_Null', NaN, ...
        'ExitFlag_Shape', NaN, ...
        'ExitFlag_Distortion', NaN, ...
        'AlphaSearchGrid', [], ...
        'AlphaSearchLogLikelihood', [], ...
        'AlphaSearchExitFlag', [], ...
        'AlphaSearchExpanded', false, ...
        'AlphaBoundaryHit', false, ...
        'AlphaSearchStopReason', "", ...
        'AlphaCandidatesEvaluated', NaN, ...
        'BinProbability_Null', {empty_bin_probability}, ...
        'BinProbability_Shape', {empty_bin_probability}, ...
        'BinProbability_Distortion', {empty_bin_probability});

    Completed = 0;
    Results = repmat(empty_result, num_simulations, 1);

    if exist(checkpoint_file, 'file')
        Saved = load(checkpoint_file);

        checkpoint_compatible = ...
            isfield(Saved, 'Results') && ...
            isfield(Saved, 'Completed') && ...
            isfield(Saved, 'Num_Bins_List') && ...
            isfield(Saved, 'Checkpoint_Settings') && ...
            isequal(Saved.Num_Bins_List(:), Num_Bins_List(:)) && ...
            isequaln( ...
                Saved.Checkpoint_Settings, ...
                Checkpoint_Settings) && ...
            Saved.Completed >= 0 && ...
            Saved.Completed <= numel(Saved.Results);

        if checkpoint_compatible
            Completed = Saved.Completed;

            if num_simulations < Completed
                error([ ...
                    'Requested %d simulations, but the compatible ', ...
                    'checkpoint already contains %d completed ', ...
                    'replications. Results were not truncated.'], ...
                    num_simulations, Completed);
            end

            if Completed > 0
                Results(1:Completed) = Saved.Results(1:Completed);
            end

            fprintf([ ...
                'Compatible checkpoint loaded: %d completed. ', ...
                'Target is %d.\n'], ...
                Completed, num_simulations);
        else
            warning([ ...
                'Ignoring an incompatible checkpoint in %s. ', ...
                'A new run will start at replication 1.'], ...
                Joint_Folder);
        end
    end

    if Completed > 0
        completed_ids = [Results(1:Completed).Simulation]';
        if ~isequal(completed_ids, (1:Completed)')
            error('Checkpoint does not contain a contiguous prefix.');
        end
    end

    Data_Const = [];
    DGP_Const = [];

    if Completed < num_simulations
        Data_Const = parallel.pool.Constant(Data);
        DGP_Const = parallel.pool.Constant(struct( ...
            'R_Axis', {Experiment.DGP_R_Axis}, ...
            'CDF', {Experiment.DGP_CDF}));

        Progress_Queue = parallel.pool.DataQueue;
        simulation_progress( ...
            'initialize', Completed, ...
            num_simulations, Experiment.Name);
        afterEach(Progress_Queue, ...
            @(simulation_id) simulation_progress( ...
                'update', simulation_id, ...
                num_simulations, Experiment.Name));
    else
        fprintf([ ...
            '%s is already complete at %d replications; ', ...
            'only output files will be rebuilt.\n'], ...
            Experiment.Name, Completed);
    end

    Model_Null = Experiment.ModelNull;
    Model_Shape = Experiment.ModelShape;
    Model_Distortion = Experiment.ModelDistortion;

    Null_Alpha = Model_Null.Alpha;
    Null_Beta = Model_Null.Beta;
    Null_Monotonicity = Model_Null.ImposeMonotonicity;
    Null_Search = Model_Null.SearchSettings;

    Shape_Alpha = Model_Shape.Alpha;
    Shape_Beta = Model_Shape.Beta;
    Shape_Monotonicity = Model_Shape.ImposeMonotonicity;
    Shape_Search = Model_Shape.SearchSettings;

    Distortion_Alpha = Model_Distortion.Alpha;
    Distortion_Beta = Model_Distortion.Beta;
    Distortion_Monotonicity = ...
        Model_Distortion.ImposeMonotonicity;
    Distortion_Search = Model_Distortion.SearchSettings;

    for batch_start = (Completed + 1):batch_size:num_simulations
        batch_end = min( ...
            batch_start + batch_size - 1, num_simulations);
        simulation_indices = batch_start:batch_end;
        num_in_batch = numel(simulation_indices);

        Batch_Results = repmat(empty_result, num_in_batch, 1);

        fprintf('\n%s: simulations %d to %d of %d\n', ...
            Experiment.Name, ...
            batch_start, batch_end, num_simulations);

        parfor q = 1:num_in_batch
            simulation_id = simulation_indices(q);
            D = Data_Const.Value;
            G = DGP_Const.Value;

            % Replication-specific deterministic stream. The same return
            % draw is used by both Case 1 and Case 2.
            rng(base_seed + simulation_id, 'twister');

            R_sim = draw_returns_from_monthly_cdf( ...
                G.R_Axis, G.CDF);

            Simulated_Return = D.Realized_Return_Template;
            Simulated_Return.realized_ret = R_sim;

            [theta_0, LL_0, ~, exit_0] = ...
                MLE_BSpline_estimation( ...
                    D.Smooth_AllR, D.Smooth_AllR_RND, ...
                    Simulated_Return, D.Risk_Free_Rate, ...
                    D.b, Null_Alpha, Null_Beta, ...
                    D.Global_Min_R, D.Global_Max_R, ...
                    Null_Monotonicity, ...
                    D.Basis_Precomputed, ...
                    Null_Search, ...
                    D.Monthly_Precomputed);

            [theta_U, LL_U, ~, exit_U] = ...
                MLE_BSpline_estimation( ...
                    D.Smooth_AllR, D.Smooth_AllR_RND, ...
                    Simulated_Return, D.Risk_Free_Rate, ...
                    D.b, Shape_Alpha, Shape_Beta, ...
                    D.Global_Min_R, D.Global_Max_R, ...
                    Shape_Monotonicity, ...
                    D.Basis_Precomputed, ...
                    Shape_Search, ...
                    D.Monthly_Precomputed);

            [theta_D, LL_D, ~, exit_D, output_D] = ...
                MLE_BSpline_estimation( ...
                    D.Smooth_AllR, D.Smooth_AllR_RND, ...
                    Simulated_Return, D.Risk_Free_Rate, ...
                    D.b, Distortion_Alpha, Distortion_Beta, ...
                    D.Global_Min_R, D.Global_Max_R, ...
                    Distortion_Monotonicity, ...
                    D.Basis_Precomputed, ...
                    Distortion_Search, ...
                    D.Monthly_Precomputed);

            alpha_hat = output_D.SelectedAlpha;
            beta_hat = output_D.SelectedBeta;

            [~, ~, ~, ~, pit_0] = log_likelihood_bspline( ...
                theta_0, R_sim, D.Risk_Free_Rate, ...
                D.Basis_Precomputed, ...
                D.Smooth_AllR, D.Smooth_AllR_RND, ...
                D.months, Null_Alpha, Null_Beta, ...
                D.Monthly_Precomputed);

            [~, ~, ~, ~, pit_U] = log_likelihood_bspline( ...
                theta_U, R_sim, D.Risk_Free_Rate, ...
                D.Basis_Precomputed, ...
                D.Smooth_AllR, D.Smooth_AllR_RND, ...
                D.months, Shape_Alpha, Shape_Beta, ...
                D.Monthly_Precomputed);

            [~, ~, ~, ~, pit_D] = log_likelihood_bspline( ...
                theta_D, R_sim, D.Risk_Free_Rate, ...
                D.Basis_Precomputed, ...
                D.Smooth_AllR, D.Smooth_AllR_RND, ...
                D.months, alpha_hat, beta_hat, ...
                D.Monthly_Precomputed);

            One = empty_result;
            One.Simulation = simulation_id;
            One.LL_Null = LL_0;
            One.LL_Shape = LL_U;
            One.LL_Distortion = LL_D;
            One.LR_Shape = 2 * (LL_U - LL_0);
            One.LR_Distortion = 2 * (LL_D - LL_0);
            One.SelectedAlpha = alpha_hat;
            One.SelectedBeta = beta_hat;
            One.ExitFlag_Null = exit_0;
            One.ExitFlag_Shape = exit_U;
            One.ExitFlag_Distortion = exit_D;
            One.AlphaSearchGrid = output_D.ParameterGrid(:)';
            One.AlphaSearchLogLikelihood = ...
                output_D.LogLikelihoodGrid(:)';
            One.AlphaSearchExitFlag = output_D.ExitFlagGrid(:)';
            One.AlphaSearchExpanded = output_D.SearchExpanded;
            One.AlphaBoundaryHit = output_D.BoundaryHit;
            One.AlphaSearchStopReason = ...
                string(output_D.SearchStopReason);
            One.AlphaCandidatesEvaluated = ...
                output_D.NumCandidatesEvaluated;

            for bin_idx = 1:num_bin_settings
                num_bins_now = num_bins_list(bin_idx);
                Stats_0 = compute_pit_statistics( ...
                    pit_0, num_bins_now);
                Stats_U = compute_pit_statistics( ...
                    pit_U, num_bins_now);
                Stats_D = compute_pit_statistics( ...
                    pit_D, num_bins_now);

                One.PIT_Sup_Null(bin_idx) = Stats_0.SupUniform;
                One.PIT_Sup_Shape(bin_idx) = Stats_U.SupUniform;
                One.PIT_Sup_Distortion(bin_idx) = ...
                    Stats_D.SupUniform;
                One.PIT_Delta_Shape(bin_idx) = max(abs( ...
                    Stats_U.BinProbability - ...
                    Stats_0.BinProbability));
                One.PIT_Delta_Distortion(bin_idx) = max(abs( ...
                    Stats_D.BinProbability - ...
                    Stats_0.BinProbability));

                One.BinProbability_Null{bin_idx} = ...
                    Stats_0.BinProbability;
                One.BinProbability_Shape{bin_idx} = ...
                    Stats_U.BinProbability;
                One.BinProbability_Distortion{bin_idx} = ...
                    Stats_D.BinProbability;

                if bin_idx == 1
                    One.KS_Null = Stats_0.KS;
                    One.KS_Shape = Stats_U.KS;
                    One.KS_Distortion = Stats_D.KS;
                end
            end

            Batch_Results(q) = One;
            send(Progress_Queue, simulation_id);
        end

        Results(simulation_indices) = Batch_Results;
        Completed = batch_end;

        save(checkpoint_file, ...
            'Results', 'Completed', ...
            'Num_Bins_List', 'Checkpoint_Settings', '-v7.3');
    end

    if ~isempty(Data_Const)
        delete(Data_Const);
    end
    if ~isempty(DGP_Const)
        delete(DGP_Const);
    end

    save(raw_file, ...
        'Results', 'Experiment', ...
        'Num_Bins_List', 'Checkpoint_Settings', '-v7.3');

    export_joint_results( ...
        Results, Experiment, Num_Bins_List, ...
        Shape_Folder, Distortion_Folder, Joint_Folder);
end


function export_joint_results( ...
    Results, Experiment, num_bins_list, ...
    shape_folder, distortion_folder, joint_folder)

    simulation_id = [Results.Simulation]';
    LL_0 = [Results.LL_Null]';
    LL_U = [Results.LL_Shape]';
    LL_D = [Results.LL_Distortion]';
    LR_Shape = [Results.LR_Shape]';
    LR_Distortion = [Results.LR_Distortion]';
    Alpha_D = [Results.SelectedAlpha]';
    Beta_D = [Results.SelectedBeta]';
    Exit_0 = [Results.ExitFlag_Null]';
    Exit_U = [Results.ExitFlag_Shape]';
    Exit_D = [Results.ExitFlag_Distortion]';
    KS_0 = [Results.KS_Null]';
    KS_U = [Results.KS_Shape]';
    KS_D = [Results.KS_Distortion]';

    Sup_0 = vertcat(Results.PIT_Sup_Null);
    Sup_U = vertcat(Results.PIT_Sup_Shape);
    Sup_D = vertcat(Results.PIT_Sup_Distortion);
    Delta_Shape = vertcat(Results.PIT_Delta_Shape);
    Delta_Distortion = vertcat(Results.PIT_Delta_Distortion);

    Expanded = [Results.AlphaSearchExpanded]';
    Boundary_Hit = [Results.AlphaBoundaryHit]';
    Num_Candidates = [Results.AlphaCandidatesEvaluated]';
    Stop_Reason = string({Results.AlphaSearchStopReason})';

    Shape_All_Summaries = table();
    Distortion_All_Summaries = table();
    Uniformity_All_Summaries = table();

    for bin_idx = 1:numel(num_bins_list)
        J = num_bins_list(bin_idx);

        shape_success = ...
            isfinite(LR_Shape) & ...
            isfinite(Delta_Shape(:, bin_idx)) & ...
            Exit_0 > 0 & Exit_U > 0;
        distortion_success = ...
            isfinite(LR_Distortion) & ...
            isfinite(Delta_Distortion(:, bin_idx)) & ...
            Exit_0 > 0 & Exit_D > 0;
        null_success = ...
            isfinite(Sup_0(:, bin_idx)) & Exit_0 > 0;

        Shape_Scalars = table( ...
            simulation_id, LL_0, LL_U, LR_Shape, ...
            Sup_0(:, bin_idx), Sup_U(:, bin_idx), ...
            Delta_Shape(:, bin_idx), ...
            KS_0, KS_U, Exit_0, Exit_U, ...
            'VariableNames', { ...
                'Simulation', 'LL_Null', 'LL_Alternative', ...
                'TestStatistic', 'PIT_Sup_Null', ...
                'PIT_Sup_Alternative', 'PIT_Pairwise_Delta', ...
                'KS_Null', 'KS_Alternative', ...
                'ExitFlag_Null', 'ExitFlag_Alternative'});

        Distortion_Scalars = table( ...
            simulation_id, LL_0, LL_D, ...
            Alpha_D, Beta_D, LR_Distortion, ...
            Sup_0(:, bin_idx), Sup_D(:, bin_idx), ...
            Delta_Distortion(:, bin_idx), ...
            KS_0, KS_D, Exit_0, Exit_D, ...
            Expanded, Boundary_Hit, ...
            Num_Candidates, Stop_Reason, ...
            'VariableNames', { ...
                'Simulation', 'LL_Null', 'LL_Alternative', ...
                'Alpha_B', 'Beta_B', 'TestStatistic', ...
                'PIT_Sup_Null', 'PIT_Sup_Alternative', ...
                'PIT_Pairwise_Delta', ...
                'KS_Null', 'KS_Alternative', ...
                'ExitFlag_Null', 'ExitFlag_Alternative', ...
                'AlphaSearchExpanded', 'AlphaBoundaryHit', ...
                'AlphaCandidatesEvaluated', ...
                'AlphaSearchStopReason'});

        writetable(Shape_Scalars, fullfile( ...
            shape_folder, sprintf( ...
                'Simulation_Scalars_Bins%d.csv', J)));
        writetable(Distortion_Scalars, fullfile( ...
            distortion_folder, sprintf( ...
                'Simulation_Scalars_Bins%d.csv', J)));

        Shape_Summary = build_case_summary( ...
            "Shape null - common constrained DGP", ...
            J, "Common null", "Unconstrained SDF", ...
            LR_Shape, Delta_Shape(:, bin_idx), ...
            Sup_0(:, bin_idx), ...
            shape_success, null_success, ...
            Experiment.ObservedLRShape, ...
            Experiment.ObservedDeltaShape(bin_idx), ...
            Experiment.ObservedSupNull(bin_idx), ...
            LL_0, LL_U, Sup_0(:, bin_idx), Sup_U(:, bin_idx));

        Distortion_Summary = build_case_summary( ...
            "Alpha-distortion null - common undistorted DGP", ...
            J, "Common null", "Alpha estimated", ...
            LR_Distortion, Delta_Distortion(:, bin_idx), ...
            Sup_0(:, bin_idx), ...
            distortion_success, null_success, ...
            Experiment.ObservedLRDistortion, ...
            Experiment.ObservedDeltaDistortion(bin_idx), ...
            Experiment.ObservedSupNull(bin_idx), ...
            LL_0, LL_D, Sup_0(:, bin_idx), Sup_D(:, bin_idx));

        writetable(Shape_Summary, fullfile( ...
            shape_folder, sprintf( ...
                'Simulation_Summary_Bins%d.csv', J)));
        writetable(Distortion_Summary, fullfile( ...
            distortion_folder, sprintf( ...
                'Simulation_Summary_Bins%d.csv', J)));

        Shape_All_Summaries = [ ...
            Shape_All_Summaries; Shape_Summary]; %#ok<AGROW>
        Distortion_All_Summaries = [ ...
            Distortion_All_Summaries; ...
            Distortion_Summary]; %#ok<AGROW>

        [uniform_p, uniform_p_plus, uniform_p95, ...
            uniform_mean, uniform_count] = tail_summary( ...
                Sup_0(null_success, bin_idx), ...
                Experiment.ObservedSupNull(bin_idx));

        Uniformity_Summary = table( ...
            J, Experiment.ObservedSupNull(bin_idx), ...
            uniform_p95, uniform_p, uniform_p_plus, ...
            uniform_count, uniform_mean, ...
            'VariableNames', { ...
                'Num_Bins', 'Observed_PIT_SupUniform', ...
                'P95_PIT_SupUniform', ...
                'Simulated_PIT_Uniformity_PValue', ...
                'PlusOne_PIT_Uniformity_PValue', ...
                'Successful_Replications', ...
                'Mean_PIT_SupUniform'});

        Uniformity_All_Summaries = [ ...
            Uniformity_All_Summaries; ...
            Uniformity_Summary]; %#ok<AGROW>

        write_mean_bins( ...
            Results, bin_idx, J, shape_success, ...
            'BinProbability_Null', ...
            'BinProbability_Shape', ...
            fullfile(shape_folder, sprintf( ...
                'Mean_PIT_Bins%d.csv', J)));

        write_mean_bins( ...
            Results, bin_idx, J, distortion_success, ...
            'BinProbability_Null', ...
            'BinProbability_Distortion', ...
            fullfile(distortion_folder, sprintf( ...
                'Mean_PIT_Bins%d.csv', J)));
    end

    writetable(Shape_All_Summaries, fullfile( ...
        shape_folder, 'Simulation_Summary_AllBins.csv'));
    writetable(Distortion_All_Summaries, fullfile( ...
        distortion_folder, 'Simulation_Summary_AllBins.csv'));
    writetable(Uniformity_All_Summaries, fullfile( ...
        joint_folder, 'Common_Null_PIT_Uniformity_Summary.csv'));

    Search_Summary = table( ...
        simulation_id, Alpha_D, Beta_D, ...
        Expanded, Boundary_Hit, Num_Candidates, Stop_Reason, ...
        'VariableNames', { ...
            'Simulation', 'SelectedAlpha', 'FixedBeta', ...
            'AlphaSearchExpanded', 'AlphaBoundaryHit', ...
            'AlphaCandidatesEvaluated', ...
            'AlphaSearchStopReason'});
    writetable(Search_Summary, fullfile( ...
        distortion_folder, 'Alpha_Search_Summary.csv'));

    save(fullfile(joint_folder, 'Alpha_Search_Paths.mat'), ...
        'Results', '-v7.3');

    fprintf('\nJoint simulation outputs were written to:\n%s\n', ...
        fileparts(joint_folder));
end


function Summary = build_case_summary( ...
    experiment_name, J, model_null, model_alternative, ...
    LR, Delta, Sup_Null, pairwise_success, null_success, ...
    observed_LR, observed_Delta, observed_Sup, ...
    LL_Null, LL_Alternative, Sup0_All, SupAlt_All)

    [lr_p, lr_p_plus, lr_p95, lr_mean, num_pairwise] = ...
        tail_summary(LR(pairwise_success), observed_LR);
    valid_lr = LR(pairwise_success);
    if isempty(valid_lr)
        lr_median = NaN;
    else
        lr_median = median(valid_lr);
    end

    [delta_p, delta_p_plus, delta_p95, delta_mean] = ...
        tail_summary(Delta(pairwise_success), observed_Delta);
    [sup_p, sup_p_plus, sup_p95, sup_mean, num_null] = ...
        tail_summary(Sup_Null(null_success), observed_Sup);

    if any(pairwise_success)
        fraction_ll_alt_greater = mean( ...
            LL_Alternative(pairwise_success) > ...
            LL_Null(pairwise_success));
        fraction_pit_alt_closer = mean( ...
            Sup0_All(pairwise_success) > ...
            SupAlt_All(pairwise_success));
    else
        fraction_ll_alt_greater = NaN;
        fraction_pit_alt_closer = NaN;
    end

    Summary = table( ...
        string(experiment_name), J, ...
        string(model_null), string(model_alternative), true, ...
        observed_LR, lr_p, lr_p_plus, ...
        observed_Delta, delta_p, delta_p_plus, ...
        string(model_null), observed_Sup, sup_p, sup_p_plus, ...
        num_pairwise, lr_mean, lr_median, lr_p95, ...
        delta_mean, delta_p95, sup_mean, sup_p95, ...
        fraction_ll_alt_greater, fraction_pit_alt_closer, ...
        num_null, ...
        'VariableNames', { ...
            'Experiment', 'Num_Bins', 'Model_A', 'Model_B', ...
            'Is_Pairwise_Null_DGP', 'Observed_LR', ...
            'Simulated_LR_PValue', 'PlusOne_LR_PValue', ...
            'Observed_PIT_Pairwise_Delta', ...
            'Simulated_PIT_Delta_PValue', ...
            'PlusOne_PIT_Delta_PValue', ...
            'PIT_Uniformity_Target_Model', ...
            'Observed_PIT_SupUniform', ...
            'Simulated_PIT_Uniformity_PValue', ...
            'PlusOne_PIT_Uniformity_PValue', ...
            'Successful_Replications', ...
            'Mean_LR', 'Median_LR', 'P95_LR', ...
            'Mean_PIT_Pairwise_Delta', ...
            'P95_PIT_Pairwise_Delta', ...
            'Mean_PIT_SupUniform', 'P95_PIT_SupUniform', ...
            'Fraction_LL_B_Greater', ...
            'Fraction_PIT_B_CloserToUniform', ...
            'Successful_Null_Uniformity_Replications'});
end


function [p_sim, p_plus, p95, mean_value, num_valid] = ...
    tail_summary(values, observed_value)

    values = values(isfinite(values));
    num_valid = numel(values);

    if num_valid == 0
        p_sim = NaN;
        p_plus = NaN;
        p95 = NaN;
        mean_value = NaN;
        return
    end

    tail_count = sum(values >= observed_value);
    p_sim = tail_count / num_valid;
    p_plus = (1 + tail_count) / (1 + num_valid);
    p95 = prctile(values, 95);
    mean_value = mean(values);
end


function write_mean_bins( ...
    Results, bin_idx, J, successful, ...
    field_A, field_B, output_file)

    num_simulations = numel(Results);
    bin_A = nan(num_simulations, J);
    bin_B = nan(num_simulations, J);

    for simulation_idx = 1:num_simulations
        cells_A = Results(simulation_idx).(field_A);
        cells_B = Results(simulation_idx).(field_B);
        bin_A(simulation_idx, :) = cells_A{bin_idx};
        bin_B(simulation_idx, :) = cells_B{bin_idx};
    end

    mean_A = mean(bin_A(successful, :), 1, 'omitnan')';
    mean_B = mean(bin_B(successful, :), 1, 'omitnan')';

    Bin_Table = table( ...
        (1:J)', ((0:J-1)' ./ J), ((1:J)' ./ J), ...
        mean_A, mean_B, ...
        'VariableNames', { ...
            'Bin', 'LowerEdge', 'UpperEdge', ...
            'MeanProbability_A', 'MeanProbability_B'});
    writetable(Bin_Table, output_file);
end


function R_sim = draw_returns_from_monthly_cdf( ...
    R_axis_cell, F_cell)

    T = numel(R_axis_cell);
    R_sim = zeros(T, 1);

    for t = 1:T
        R_axis_t = R_axis_cell{t}(:);
        F_t = F_cell{t}(:);

        [F_unique, idx_unique] = unique(F_t, 'stable');
        R_unique = R_axis_t(idx_unique);

        if numel(F_unique) < 2
            error([ ...
                'Physical CDF at t=%d has fewer than ', ...
                'two unique values.'], t);
        end

        u = rand;
        R_sim(t) = interp1( ...
            F_unique, R_unique, u, 'linear', 'extrap');
    end
end


function simulation_progress( ...
    action, value, total, experiment_name)

    persistent Completed_Count
    persistent Starting_Count
    persistent Total_Count
    persistent Progress_Timer
    persistent Experiment_Name

    switch action
        case 'initialize'
            Completed_Count = value;
            Starting_Count = value;
            Total_Count = total;
            Progress_Timer = tic;
            Experiment_Name = char(experiment_name);

            fprintf('\n==================================================\n');
            fprintf('Starting experiment: %s\n', Experiment_Name);
            fprintf('Previously completed: %d/%d\n', ...
                Completed_Count, Total_Count);
            fprintf('==================================================\n');

        case 'update'
            Completed_Count = Completed_Count + 1;
            Newly_Completed = Completed_Count - Starting_Count;
            Elapsed_Seconds = toc(Progress_Timer);
            Average_Seconds = ...
                Elapsed_Seconds / max(Newly_Completed, 1);
            Remaining_Seconds = ...
                (Total_Count - Completed_Count) * Average_Seconds;

            fprintf([ ...
                '[%s] Completed %d/%d (%.1f%%) | ', ...
                'elapsed %.1f min | ETA %.1f min\n'], ...
                Experiment_Name, ...
                Completed_Count, Total_Count, ...
                100 * Completed_Count / Total_Count, ...
                Elapsed_Seconds / 60, Remaining_Seconds / 60);
    end
end
