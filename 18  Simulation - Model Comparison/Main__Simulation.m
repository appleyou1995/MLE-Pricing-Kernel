    if isempty(Pool)
        Local_Cluster = parcluster('local');
        Actual_Num_Workers = min( ...
            Requested_Num_Workers, Local_Cluster.NumWorkers);
        Pool = parpool(Local_Cluster, Actual_Num_Workers);
    else
        Actual_Num_Workers = Pool.NumWorkers;
    end

    Batch_Size = max( ...
        Actual_Num_Workers, ...
        Batch_Size_Multiplier * Actual_Num_Workers);

    fprintf('\nParallel workers: %d. Batch size: %d.\n', ...
        Actual_Num_Workers, Batch_Size);

    Joint_Results = run_simulation_experiment( ...
        Joint_Experiment, Data, ...
        Num_Simulations, Num_Bins_List, ...
        Base_Seed, Batch_Size, Path_Output_18);
end


